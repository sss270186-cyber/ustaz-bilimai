const fs = require('node:fs');
const {topics,tasks} = require('./measurement.cjs');
const quote = s => "'" + String(s).replaceAll("'", "''") + "'";
let sql = '-- Generated by node scripts/build-seed.cjs. Private: never serve this file.\nbegin;\n';
for (const t of topics) sql += `insert into public.unt_topics(id,position,title,ready) values (${quote(t.id)},${t.position},${quote(t.title)},${t.ready});\n`;
for (const t of tasks) {
  const keys=['id','topic_id','level','position','title','prompt','given_data','find_value','formulas','unit'];
  const vals=keys.map(k=>k==='position'? t[k] : quote(k==='formulas'?JSON.stringify(t[k]):t[k]));
  sql+=`insert into public.unt_tasks(${keys.join(',')}) values (${vals.join(',')});\n`;
  sql+=`insert into unt_private.answer_keys(task_id,answer,steps) values (${quote(t.id)},${quote(t.answer)},${quote(JSON.stringify(t.steps))});\n`;
}
sql+='commit;\n';
const file='supabase/migrations/202610180002_measurement_seed.sql';
if(process.argv.includes('--check')) {if(fs.readFileSync(file,'utf8')!==sql)throw Error('Seed is out of date');}
else fs.writeFileSync(file,sql);
